        /* ─── Navbar scroll behaviour ─── */
        const navbar = document.getElementById('indexNavbar');
        window.addEventListener('scroll', () => {
            if (!navbar) return;
            if (window.scrollY > 10) {
                navbar.classList.add('index_navbar_section--scrolled');
            } else {
                navbar.classList.remove('index_navbar_section--scrolled');
            }
        }, {
            passive: true
        });

        /* ─── Mobile menu open/close ─── */
        // Scope all menu controls to the visible, new navbar. There are legacy
        // menu elements above it with the same IDs, so document.getElementById()
        // would otherwise open the hidden legacy drawer instead.
        const navbarRoot = document.querySelector('.new_navbr_section');
        const burger = navbarRoot?.querySelector('#navBurger');
        const offcanvas = navbarRoot?.querySelector('#navOffcanvas');
        const backdrop = navbarRoot?.querySelector('#navBackdrop');
        const closeBtn = navbarRoot?.querySelector('#navClose');

        function openMenu() {
            offcanvas.classList.add('active');
            backdrop.classList.add('active');
            document.body.style.overflow = 'hidden';
        }

        function closeMenu() {
            offcanvas.classList.remove('active');
            backdrop.classList.remove('active');
            document.body.style.overflow = '';
        }

        if (burger && offcanvas && backdrop && closeBtn) {
            burger.addEventListener('click', openMenu);
            closeBtn.addEventListener('click', closeMenu);
            backdrop.addEventListener('click', closeMenu);
        }

        /* ─── Mobile accordion (+ toggle for sub-services) ─── */
        document.querySelectorAll('.index_navbar_section__mob-item[data-has-sub]').forEach(item => {
            const row = item.querySelector('.index_navbar_section__mob-row');
            if (!row) return;
            row.addEventListener('click', () => {
                const isOpen = item.classList.contains('open');
                // Close all others
                document.querySelectorAll('.index_navbar_section__mob-item.open').forEach(el => el.classList.remove('open'));
                if (!isOpen) item.classList.add('open');
            });
        });

        async function loadNavbarCategories() {
            const desktopMenu = navbarRoot?.querySelector('#navbarCategoryDesktop');
            const mobileMenu = navbarRoot?.querySelector('#navbarCategoryMobile');
            const categories = [
                ['Skin Care', 'skin-care', 'skin_care.php'],
