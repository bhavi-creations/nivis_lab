            const itemsHtml = categories.map(([label, slug, href]) =>
                `<li><a href="${href}">${label}</a></li>`
            ).join('');

            if (desktopMenu) desktopMenu.innerHTML = itemsHtml;
            if (mobileMenu) mobileMenu.innerHTML = itemsHtml;
        }

