<script>
    (function() {
        const sections = Array.from(document.querySelectorAll('[data-backend-category]'));

        function escapeHtml(value) {
            return String(value ?? '').replace(/[&<>"']/g, function(character) {
                return {
                    '&': '&amp;',
                    '<': '&lt;',
                    '>': '&gt;',
                    '"': '&quot;',
                    "'": '&#039;'
                } [character];
            });
        }

        function productCard(product) {
            const image = product.imageUrl || './assets/img/product.webp';
            const link = product.link && product.link !== '#' ? product.link : '#';
            const description = product.subtitle || product.description || 'Skincare product for your routine.';
            const price = product.price ? `<div class="product-price">${escapeHtml(product.price)}</div>` : '';

            return `
            <div class="col-md-4">
                <article class="skinthesis-card h-100">
                    <a class="skincare-product-image-link" href="${escapeHtml(link)}">
                        <div class="card-img-wrapper">
                            <img src="${escapeHtml(image)}" class="card-img-top skincare-product-image"
                                alt="${escapeHtml(product.name || 'Skincare product')}" loading="lazy"
                                onerror="this.onerror=null;this.src='./assets/img/product.webp';">
                        </div>
                    </a>
                    <div class="card-body p-4">
                        <h4 class="card-title">${escapeHtml(product.name || 'Skincare product')}</h4>
                        <p class="card-text text-muted small">${escapeHtml(description)}</p>
                        ${price}
                        <a href="${escapeHtml(link)}" class="read-more-link">View Product &rarr;</a>
                    </div>
                </article>
            </div>
        `;
        }

        async function fetchProducts(category) {
            const response = await fetch(`fetch_category_products.php?category=${encodeURIComponent(category)}`, {
                headers: {
                    Accept: 'application/json'
                }
            });
            if (!response.ok) throw new Error('Product request failed');
            const result = await response.json();
            return Array.isArray(result.products) ? result.products : [];
        }

        async function loadSection(section) {
            const category = section.dataset.backendCategory;
            const grid = section.querySelector('.row');

            try {
                const products = await fetchProducts(category);

                if (products.length) {
                    if (grid) grid.innerHTML = products.slice(0, 3).map(productCard).join('');
                    return;
                }

            } catch (error) {
                // Keep the existing cards when the backend is temporarily unavailable.
            }
        }

        sections.forEach(loadSection);
    }());
</script>

