<script>
    const cartDrawerEl = document.getElementById('cartDrawer');
    const cartContentEl = document.getElementById('cartContent');
    let cartItems = window.NivisCart ? window.NivisCart.read() : [];
    let cartOffcanvas = null;

    function formatPrice(value) {
        const amount = Number(value || 0);
        return isNaN(amount) ? '₹0' : `₹${amount.toFixed(0)}`;
    }

    function getProductInfoFromCard(card) {
        if (!card) return null;
        const nameEl = card.querySelector('.product-name');
        const priceEl = card.querySelector('.product-price');
        const imgEl = card.querySelector('.product-img-wrap img.img-primary, .product-img-wrap img, img');
        const name = nameEl ? nameEl.textContent.trim() : 'Product';
        const salePriceEl = card.querySelector('[data-sale-price]');
        const priceText = String(card.dataset.price || card.dataset.productPrice || salePriceEl?.dataset.salePrice || priceEl?.textContent || '0')
            .replace(/,/g, '').replace(/[^0-9.]/g, '').trim();
        const sku = card.dataset.sku || card.dataset.productSku || card.dataset.productCode || '';

        return {
            id: sku || card.dataset.productId || name.replace(/\s+/g, '_').toLowerCase(),
            sku,
            name,
            price: Number(priceText) || Number(card.dataset.price) || 0,
            image: imgEl ? imgEl.src : '',
            quantity: 1,
        };
    }

    function removeFromCart(itemId) {
        if (!window.NivisCart) return;
        window.NivisCart.remove(itemId);
        renderCart();
    }

    let cartRelatedCatalog = null;
    let cartRelatedRequest = null;

    function relatedProductKey(value) {
        return String(value || '').trim().toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
    }

    function sameRelatedProduct(product, item) {
        const keys = [product.sku, product.id, product.urlKey, product.name].map(relatedProductKey).filter(Boolean);
        return [item.sku, item.id, item.name].map(relatedProductKey).filter(Boolean).some(key => keys.includes(key));
    }

    function getRelatedProducts() {
        if (!cartItems.length) return [];
        if (cartRelatedCatalog === null) {
            if (!cartRelatedRequest) {
                cartRelatedRequest = fetch(new URL('fetch_category_products.php?category=all', window.location.href))
                    .then(response => {
                        if (!response.ok) throw new Error('Unable to load related products');
                        return response.json();
                    })
                    .then(result => {
                        const products = result.data?.products || result.products;
                        cartRelatedCatalog = Array.isArray(products) ? products : [];
                        renderCart();
                    })
                    .catch(() => { cartRelatedRequest = null; });
            }
            return [];
        }

        const sources = cartItems.map(item => cartRelatedCatalog.find(product => sameRelatedProduct(product, item))).filter(Boolean);
        const tokens = value => String(value || '').toLowerCase().split(/[,|;]+/).map(value => value.trim())
            .filter(value => value && !['all', 'products', 'product', 'skincare', 'skin care'].includes(value));
        const overlaps = (left, right) => tokens(left).some(value => tokens(right).includes(value));
        const seen = new Set();

        return cartRelatedCatalog
            .filter(product => !cartItems.some(item => sameRelatedProduct(product, item)))
            .map(product => ({
                product,
                score: sources.reduce((best, source) => Math.max(best,
                    (overlaps(product.category, source.category) ? 4 : 0) +
                    (overlaps(product.displayConcern || product.concern, source.displayConcern || source.concern) ? 3 : 0) +
                    (overlaps(product.type, source.type) ? 2 : 0) +
                    (overlaps(product.ingredient, source.ingredient) ? 1 : 0)), 0)
            }))
            .filter(entry => entry.score > 0)
            .sort((left, right) => right.score - left.score)
            .filter(({ product }) => {
                const key = relatedProductKey(product.sku || product.id || product.name);
                if (!key || seen.has(key)) return false;
                seen.add(key);
                return true;
            })
            .slice(0, 4)
            .map(({ product }) => ({
                id: relatedProductKey(product.sku || product.id || product.name),
                sku: product.sku || '',
                name: product.name || '',
                price: Number(product.priceNumber ?? String(product.price || '0').replace(/[^0-9.]/g, '')) || 0,
                image: product.imageUrl || product.images?.[0] || '',
                sub: product.displayConcern || product.category || product.type || ''
            }));
    }

    function escapeRelatedHtml(value) {
        return String(value ?? '').replace(/[&<>"']/g, character => ({
            '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
        })[character]);
    }

    function addRelatedToCart(itemId, itemName, itemPrice, itemImage, sku = '', quantity = 1) {
        if (!window.NivisCart) return;
        window.NivisCart.add({
            id: itemId,
            sku,
            name: itemName,
            price: itemPrice,
            image: itemImage
        }, quantity);
        renderCart();
        openCartDrawer();
    }

    function renderCart() {
        if (!cartContentEl) return;
        cartItems = window.NivisCart ? window.NivisCart.read() : cartItems;

        if (cartItems.length === 0) {
            cartContentEl.innerHTML = `
                <div class="text-center py-4">
                    <p class="mb-2">Your cart is empty.</p>
                    <p class="text-muted">Click Add to Cart on any product to view it here.</p>
                </div>
            `;
            return;
        }

        const totalAmount = cartItems.reduce((sum, item) => sum + item.price * item.quantity, 0);

        const productHtml = cartItems.map(item => `
            <div class="d-flex align-items-center mb-3 pb-3 border-bottom" style="position: relative;">
                <div class="me-3" style="width: 60px; min-width: 60px;">
                    <img src="${item.image}" alt="${item.name}" class="img-fluid rounded" />
                </div>
                <div class="flex-grow-1">
                    <div class="fw-bold" style="font-size: 14px;">${item.name}</div>
                    <div class="text-muted small">${formatPrice(item.price)} x ${item.quantity}</div>
                </div>
                <div class="fw-bold me-3">${formatPrice(item.price * item.quantity)}</div>
                <button onclick="removeFromCart('${item.id}')" class="btn btn-sm btn-dark" title="Remove">
                    <i class="fas fa-trash"></i> Remove
                </button>
            </div>
        `).join('');

        const relatedProducts = getRelatedProducts();
        const relatedProductsHtml = relatedProducts.length > 0 ? `
            <div class="mt-3 pt-3 border-top">
                <h6 class="mb-3" style="font-size: 14px;">You might also like</h6>
                ${relatedProducts.map((product, idx) => `
                    <div class="border-bottom pb-3 mb-3">
                        <div style="display: flex; gap: 12px; align-items: flex-start;">
                            <div style="width: 70px; min-width: 70px;">
                                <img src="${escapeRelatedHtml(product.image)}" alt="${escapeRelatedHtml(product.name)}" style="width: 100%; height: 70px; object-fit: cover; border-radius: 4px;" />
                            </div>
                            <div style="flex: 1; font-size: 13px;">
                                <div class="fw-bold" style="margin-bottom: 2px; font-size: 14px;">${escapeRelatedHtml(product.name.substring(0, 35))}${product.name.length > 35 ? '...' : ''}</div>
                                <div class="text-muted small" style="margin-bottom: 4px;">${escapeRelatedHtml(product.sub.substring(0, 40))}${product.sub.length > 40 ? '...' : ''}</div>
                                <div class="fw-bold nivis-product-price" style="color: #d32f2f; margin-bottom: 6px;">${formatPrice(product.price)}</div>
                                <button type="button" data-related-index="${idx}" class="btn btn-sm btn-dark" style="font-size: 12px;">Add</button>
                            </div>
                        </div>
                    </div>
                `).join('')}
            </div>
        ` : '';

        cartContentEl.innerHTML = `
            <div class="cart-items">
                ${productHtml}
            </div>
            ${relatedProductsHtml}
            <div class="border-top pt-3 mt-3">
                <div class="d-flex justify-content-between align-items-center mb-3">
                    <strong>Subtotal</strong>
                    <strong>${formatPrice(totalAmount)}</strong>
                </div>
                <div class="d-grid gap-2">
                    <button type="button" class="btn btn-dark" id="checkoutPageBtn">Proceed to Checkout</button>
                </div>
            </div>
        `;
    }

    cartContentEl?.addEventListener('click', event => {
        const button = event.target.closest('[data-related-index]');
        if (!button) return;
        const product = getRelatedProducts()[Number(button.dataset.relatedIndex)];
        if (product) addRelatedToCart(product.id, product.name, product.price, product.image, product.sku);
    });

    function goToCheckoutPage() {
        if (!window.NivisCart) return;

        const cart = window.NivisCart.toCart();
        if (!cart.items.length || cart.total <= 0) {
            alert('Your cart is empty.');
            return;
        }

        window.location.href = 'checkout.php';
    }

    function openCartDrawer() {
        if (!cartOffcanvas || !cartDrawerEl) return;
        cartOffcanvas.show();
    }

    function addProductToCart(item) {
        if (!window.NivisCart || !item || !item.name) return;
        window.NivisCart.add(item, item.quantity || 1);
        renderCart();
        openCartDrawer();
    }

    window.addProductToCart = addProductToCart;

    function initFooterCart() {
        if (window.__nivisFooterCartReady) return;
        window.__nivisFooterCartReady = true;

        cartItems = window.NivisCart ? window.NivisCart.read() : [];
        cartOffcanvas = window.bootstrap ? bootstrap.Offcanvas.getOrCreateInstance(cartDrawerEl) : null;
        renderCart();
        cartDrawerEl.addEventListener('show.bs.offcanvas', renderCart);

        document.body.addEventListener('click', event => {
            const checkoutButton = event.target.closest('#checkoutPageBtn');
            if (checkoutButton) {
                event.preventDefault();
                goToCheckoutPage();
                return;
            }

            const button = event.target.closest('.btn-cart, .video_section_add_btn');
            if (!button) return;

            const card = button.closest('.product-card');
            const product = window.NivisCart ? window.NivisCart.fromCard(card) : getProductInfoFromCard(card);
            if (!product) return;

            addProductToCart(product);
            event.preventDefault();
        });

        window.addEventListener('nivis-cart:updated', renderCart);
    }

    function ensureNivisCart(callback) {
        if (window.NivisCart) {
            callback();
            return;
        }

        const existingScript = document.querySelector('script[src*="graphql-client.js"]');
        const script = existingScript || document.createElement('script');
        let attempts = 0;

        const waitForCart = () => {
            if (window.NivisCart || attempts >= 20) {
                callback();
                return;
            }

            attempts += 1;
            setTimeout(waitForCart, 100);
        };

        script.addEventListener('load', waitForCart, {
            once: true
        });

        script.addEventListener('error', waitForCart, {
            once: true
        });

        if (!existingScript) {
            script.src = 'assets/js/graphql-client.js?v=6';
            document.head.appendChild(script);
        } else {
            waitForCart();
        }
    }

    function bootFooterCart() {
        if (!cartDrawerEl || !cartContentEl) return;
        ensureNivisCart(initFooterCart);
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', bootFooterCart, {
            once: true
        });
    } else {
        bootFooterCart();
    }
</script>
